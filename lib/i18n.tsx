"use client";

/**
 * Languages for the fisherman console.
 *
 * A skipper on the Andhra or Kerala coast is not going to read an English
 * safety verdict on a wet phone screen, so the whole fisherman side runs in
 * the language they pick and the parts that matter most can be read out loud.
 *
 * English is the base dictionary. Every other language is a partial of it:
 * a key that has not been translated yet falls through to English rather than
 * rendering a key name, which keeps the screen usable while the coverage
 * grows. Nothing here is machine-translated at runtime — these are fixed
 * strings shipped with the app, so they work with no signal.
 */

import * as React from "react";

/* ------------------------------------------------------------------ */
/* Languages                                                           */
/* ------------------------------------------------------------------ */

export type LangCode =
  | "en"
  | "hi"
  | "te"
  | "ta"
  | "ml"
  | "kn"
  | "or"
  | "bn"
  | "mr"
  | "gu";

export interface Language {
  code: LangCode;
  /** What the language calls itself — the only label a speaker will scan for. */
  native: string;
  english: string;
  /** BCP-47 tag handed to the speech synthesiser. */
  speech: string;
}

export const LANGUAGES: Language[] = [
  { code: "en", native: "English", english: "English", speech: "en-IN" },
  { code: "hi", native: "हिन्दी", english: "Hindi", speech: "hi-IN" },
  { code: "te", native: "తెలుగు", english: "Telugu", speech: "te-IN" },
  { code: "ta", native: "தமிழ்", english: "Tamil", speech: "ta-IN" },
  { code: "ml", native: "മലയാളം", english: "Malayalam", speech: "ml-IN" },
  { code: "kn", native: "ಕನ್ನಡ", english: "Kannada", speech: "kn-IN" },
  { code: "or", native: "ଓଡ଼ିଆ", english: "Odia", speech: "or-IN" },
  { code: "bn", native: "বাংলা", english: "Bengali", speech: "bn-IN" },
  { code: "mr", native: "मराठी", english: "Marathi", speech: "mr-IN" },
  { code: "gu", native: "ગુજરાતી", english: "Gujarati", speech: "gu-IN" },
];

export function languageFor(code: LangCode): Language {
  return LANGUAGES.find((item) => item.code === code) || LANGUAGES[0];
}

