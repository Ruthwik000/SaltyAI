const STORAGE_KEY = "salty_lang";
const listeners = new Set<() => void>();
let snapshot: LangCode | null = null;

function readStored(): LangCode {
  if (typeof window === "undefined") return "en";
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    if (raw && DICTIONARIES[raw as LangCode]) return raw as LangCode;
  } catch {
    // storage blocked — English it is
  }
  return "en";
}

function subscribe(listener: () => void) {
  listeners.add(listener);
  if (typeof window !== "undefined") {
    // A second tab (or a second SALTY window on the same phone) switching
    // language should move this one too.
    window.addEventListener("storage", listener);
  }
  return () => {
    listeners.delete(listener);
    if (typeof window !== "undefined") window.removeEventListener("storage", listener);
  };
}

function getSnapshot(): LangCode {
  if (snapshot === null) snapshot = readStored();
  return snapshot;
}

export function setLanguage(code: LangCode) {
  try {
    window.localStorage.setItem(STORAGE_KEY, code);
    document.documentElement.lang = code;
  } catch {
    // ignore
  }
  snapshot = code;
  listeners.forEach((listener) => listener());
}

export function useLanguage(): LangCode {
  return React.useSyncExternalStore(subscribe, getSnapshot, () => "en" as LangCode);
}

/** Fill `{name}` placeholders. */
function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in vars ? String(vars[key]) : match
  );
}

export function translate(
  lang: LangCode,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const value = DICTIONARIES[lang]?.[key] ?? en[key] ?? key;
  return interpolate(value, vars);
}

export type TFunction = (
  key: TranslationKey,
  vars?: Record<string, string | number>
) => string;

/**
 * `t` for the current language, plus the language itself for anything that
 * needs the raw code (speech, `lang` attributes, number formatting).
 */
export function useT(): { t: TFunction; lang: LangCode; language: Language } {
  const lang = useLanguage();
  const t = React.useCallback<TFunction>((key, vars) => translate(lang, key, vars), [lang]);
  return { t, lang, language: languageFor(lang) };
}

