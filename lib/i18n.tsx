export function speechSupported(): boolean {
  return typeof window !== "undefined" && "speechSynthesis" in window;
}

/**
 * Pick the closest installed voice: an exact locale match first, then any
 * voice for the same language, then whatever the device defaults to. A phone
 * with no Telugu voice will read the Telugu text in its default voice, which
 * is rough but better than silence.
 */
function pickVoice(tag: string): SpeechSynthesisVoice | undefined {
  const voices = window.speechSynthesis.getVoices();
  const exact = voices.find((voice) => voice.lang.toLowerCase() === tag.toLowerCase());
  if (exact) return exact;
  const base = tag.split("-")[0].toLowerCase();
  return voices.find((voice) => voice.lang.toLowerCase().startsWith(base));
}

export interface SpeechControls {
  speak: (text: string) => void;
  stop: () => void;
  speaking: boolean;
  supported: boolean;
}

/**
 * Read text out in the language currently selected.
 *
 * Uses the browser's own speech synthesiser, so it needs no network and no
 * key — which matters on a boat. Whether a given Indian language has a voice
 * installed is the device's business; `supported` only reports whether the
 * API exists at all.
 */
export function useSpeech(): SpeechControls {
  const { language } = useT();
  const [speaking, setSpeaking] = React.useState(false);
  const supported = React.useSyncExternalStore(
    () => () => {},
    () => speechSupported(),
    () => false
  );

  React.useEffect(() => {
    return () => {
      if (speechSupported()) window.speechSynthesis.cancel();
    };
  }, []);

  const stop = React.useCallback(() => {
    if (!speechSupported()) return;
    window.speechSynthesis.cancel();
    setSpeaking(false);
  }, []);

  const speak = React.useCallback(
    (text: string) => {
      if (!speechSupported() || !text.trim()) return;
      window.speechSynthesis.cancel();

      const utterance = new SpeechSynthesisUtterance(text);
      utterance.lang = language.speech;
      const voice = pickVoice(language.speech);
      if (voice) utterance.voice = voice;
      // Slightly slower than default: this is read over engine noise.
      utterance.rate = 0.95;
      utterance.onend = () => setSpeaking(false);
      utterance.onerror = () => setSpeaking(false);

      setSpeaking(true);
      window.speechSynthesis.speak(utterance);
    },
    [language.speech]
  );

  return { speak, stop, speaking, supported };
}
